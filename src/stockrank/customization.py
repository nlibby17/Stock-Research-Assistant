class PersonalizationUpdateError(RuntimeError):
    """Raised when local personalization cannot be safely applied or restored."""


@dataclass
class _FileChange:
    path: Path
    content: str | None
    staged: Path | None = None
    backup: Path | None = None
    installed: bool = False


def _next_backup_path(path: Path) -> Path:
    index = 0
    while True:
        suffix = ".bak" if index == 0 else f".bak.{index}"
        candidate = path.with_name(path.name + suffix)
        if not candidate.exists():
            return candidate
        index += 1


def _stage_text(path: Path, content: str) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    staged = path.with_name(f"{path.name}.{uuid4().hex}.tmp")
    try:
        staged.write_text(content, encoding="utf-8")
    except Exception:
        try:
            staged.unlink(missing_ok=True)
        except OSError:
            pass
        raise
    return staged


def _backup_active_file(path: Path, backup: Path) -> None:
    os.replace(path, backup)


def _install_staged_file(staged: Path, path: Path) -> None:
    os.replace(staged, path)


def _restore_backup_file(backup: Path, path: Path) -> None:
    os.replace(backup, path)


def _preserve_unbacked_active_file(path: Path) -> Path:
    recovery = path.with_name(f"{path.name}.failed.{uuid4().hex}")
    os.replace(path, recovery)
    return recovery


def _reload_local_customization(root: Path) -> None:
    load_settings(root)


def _render_local_universe(securities: Iterable[Security]) -> str:
    output = io.StringIO(newline="")
    writer = csv.writer(output, lineterminator="\n")
    writer.writerow(("ticker", "company", "sector"))
    for security in securities:
        writer.writerow((security.ticker, security.company, security.sector))
    return output.getvalue()


